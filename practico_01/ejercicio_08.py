"""Any y Sets."""

from typing import Any, Iterable


def superposicion_basico(lista_1: Iterable[Any], lista_2: Iterable[Any]) -> bool:
    """Toma dos listas y devuelve un booleano en base a si tienen al menos 1
    elemento en común.

    Restricción: Utilizar bucles anidados.
    """

    # Los bucles anidados comparan cada par posible; el return anticipado corta
    # apenas aparece el primer elemento en común.
    for a in lista_1:
        for b in lista_2:
            if a == b:
                return True

    return False


